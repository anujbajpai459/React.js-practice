//var - old way of creating variables. 
//problem with var - it can be re-declared and updated 
var name="anuj";
console.log(name);

//let - Modern wayand used when value can change.
let age = 22;
age = 23;
console.log(age);

// const - used when value should Not change
 const pi=3.14;
 console.log(pi);
 
//notes-var is old and function-scoped, let allows value updates, and const creates fixed values that cannot be changed.
